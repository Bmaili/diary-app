function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619)
  return h >>> 0
}

export interface DailyPoem {
  poem: Poem
  /** 为什么是这句：今日中秋、今日寒露、寒露时节、秋日 */
  reason: string
}

const SEASON_NAME = { spring: '春日', summer: '夏日', autumn: '秋日', winter: '冬日' } as const

/** offset：点“换一首”的次数 */
export function poemFor(date: string, offset = 0): DailyPoem {
  const info = lunarDay(date)
  const special = info.festival ?? info.jieqi
  const first = special ? POEMS.find((p) => p.tags.includes(special)) : undefined
  const season = seasonOf(info.term)
  const termPoem = POEMS.find((p) => p.tags.includes(info.term))
  const pool = [
    ...(termPoem && termPoem !== first ? [termPoem] : []),
    ...POEMS.filter((p) => p.tags.includes(season)),
    ...POEMS.filter((p) => p.tags.includes('any')),
  ]
  if (first && offset === 0) return { poem: first, reason: `今日${special}` }
  const k = first ? offset - 1 : offset
  const poem = pool[(hash(date) + k) % pool.length]
  return { poem, reason: poem === termPoem ? `${info.term}时节` : poem.tags.includes('any') ? info.term : SEASON_NAME[season] }
}
