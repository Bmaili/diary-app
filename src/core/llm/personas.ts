/**
 * 问答的人物（2026-10-19 加入，规格 7.3）：同一套“怎么翻日记”的方法，换不同的人陪你聊。
 *
 * - 内置六个，不能改（以后改进了大家都能用上）；可以另外添加自己的人物，也可以照着内置的改一份。
 * - 人物只管身份和语气。计数、引文、心情不好的日子只陪伴这些底线由代码接在后面（PERSONA_RULES），
 *   写明优先于人物设定，自定义人物也改不掉。
 * - 首屏问候：内置人物按时段各有几句自己的口吻（greetingLines），自定义人物没有，用节令和日记里的句子。
 */

export type GreetSlot = 'morning' | 'day' | 'evening' | 'night'

export interface Persona {
  id: string
  name: string
  /** 一句话介绍，选人物时显示 */
  desc: string
  /** 说话的样子：接进系统提示词（内置人物也是“照着现成的改”时拿过去的那段，所以不超过 STYLE_MAX） */
  style: string
  /** 一句例句：选人物时显示，也告诉模型大概的语气 */
  example?: string
  /** 小印章上的一个字；自定义人物用名字的第一个字 */
  seal?: string
  custom?: boolean
  /** 心情不好、说起难过的事时，这个人物怎么陪（2026-10-22 加入，只有内置人物有） */
  low?: string
  /** 示范问答（2026-10-22 加入，只有内置人物有）：虚构的人和事，只给模型看口吻和分寸 */
  samples?: { q: string; a: string }[]
}

/** 用户添加的人物（存在 prefs.ai.personas） */
export interface CustomPersona {
  id: string
  name: string
  style: string
  example?: string
}

